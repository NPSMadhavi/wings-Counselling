export function getSupportTopicBySlug(slug) {
  return SUPPORT_TOPICS.find((topic) => topic.slug === slug) || null;
}

export function getSupportTopicPath(slug) {
  return `/support/${slug}`;
}

function matchesKeywords(text, keywords = []) {
  if (!keywords.length) return true;
  const haystack = String(text || "").toLowerCase();
  return keywords.some((keyword) => haystack.includes(keyword.toLowerCase()));
}

export function filterArticlesForTopic(articles, topic) {
  if (!topic?.articleKeywords?.length) return articles;
  const filtered = articles.filter((article) =>
    matchesKeywords(
      `${article.title} ${article.excerpt || article.desc || ""} ${article.category} ${article.content || ""}`,
      topic.articleKeywords
    )
  );
  return filtered.length ? filtered : articles;
}

export function filterServicesForTopic(services, topic) {
  if (!topic?.serviceKeywords?.length) return services.slice(0, 3);
  const filtered = services.filter((service) =>
    matchesKeywords(
      `${service.title} ${service.desc || service.description || ""} ${service.parentName}`,
      topic.serviceKeywords
    )
  );
  return (filtered.length ? filtered : services).slice(0, 3);
}
